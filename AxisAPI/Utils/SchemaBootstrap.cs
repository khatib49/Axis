using Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;

namespace AxisAPI.Utils
{
    /// <summary>
    /// Creates the tables of small, additive features when the API starts, so a publish is enough
    /// (no SQL to run by hand). Each script is idempotent: it checks __EFMigrationsHistory and
    /// does nothing once the migration is recorded. Failures are logged and never stop the API.
    /// </summary>
    public static class SchemaBootstrap
    {
        // Same as docs/sql/20261115_Menu4D.sql (dotnet ef migrations script --idempotent).
        private const string Menu4D = """
START TRANSACTION;


DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261115004335_Menu4D') THEN
    CREATE TABLE "Menu4D_Profiles" (
        "Id" integer GENERATED BY DEFAULT AS IDENTITY,
        "ItemId" integer NOT NULL,
        "PartsJson" text,
        "PartsPublished" boolean NOT NULL,
        "RealSizeCm" numeric(6,1),
        "GenStatus" character varying(20) NOT NULL,
        "GenProvider" character varying(40),
        "GenTaskId" character varying(120),
        "GenProgress" integer NOT NULL,
        "GenError" character varying(1000),
        "GenQueuedOn" timestamp with time zone,
        "GenStartedOn" timestamp with time zone,
        "GenFinishedOn" timestamp with time zone,
        "UpdatedOn" timestamp with time zone NOT NULL,
        "UpdatedBy" character varying(256) NOT NULL,
        CONSTRAINT "PK_Menu4D_Profiles" PRIMARY KEY ("Id"),
        CONSTRAINT "FK_Menu4D_Profiles_Items_ItemId" FOREIGN KEY ("ItemId") REFERENCES "Items" ("Id") ON DELETE CASCADE
    );
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261115004335_Menu4D') THEN
    CREATE INDEX "IX_Menu4D_Profiles_GenStatus" ON "Menu4D_Profiles" ("GenStatus");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261115004335_Menu4D') THEN
    CREATE UNIQUE INDEX "IX_Menu4D_Profiles_ItemId" ON "Menu4D_Profiles" ("ItemId");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261115004335_Menu4D') THEN
    INSERT INTO "__EFMigrationsHistory" ("MigrationId", "ProductVersion")
    VALUES ('20261115004335_Menu4D', '8.0.11');
    END IF;
END $EF$;
COMMIT;
""";

        public static void Apply(WebApplication app)
        {
            using var scope = app.Services.CreateScope();
            var log = scope.ServiceProvider.GetRequiredService<ILoggerFactory>().CreateLogger("SchemaBootstrap");
            try
            {
                var db = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
                db.Database.SetCommandTimeout(60);
                db.Database.ExecuteSqlRaw(Menu4D);
                log.LogInformation("Schema bootstrap: Menu4D checked.");
            }
            catch (Exception ex)
            {
                log.LogError(ex, "Schema bootstrap failed for Menu4D; run docs/sql/20261115_Menu4D.sql by hand.");
            }
        }
    }
}
